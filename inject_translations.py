def main():
    papers = json.load(open(PAPERS, encoding="utf-8"))
    n_tr = 0
    for p in papers:
        doi = p.get("doi", "")
        if doi in TR:
            t = TR[doi]
            p["abstract_zh"] = t["abstract_zh"]
            p["summary_zh"] = t["summary_zh"]
            p["highlight"] = t["highlight"]
            n_tr += 1
    # 清理 11 篇 JAAD 中不准确的 "RSS 源未提供摘要" 表述（它们确实任何来源都无摘要）
    n_clean = 0
    for p in papers:
        s = p.get("summary_zh", "")
        if "RSS" in s and "未提供摘要" in s:
            # 改写为基于题目的简洁描述，去掉误导性括号
            p["summary_zh"] = "（该文献来源未提供结构化摘要，以下仅基于题目概述：" + (p.get("title_zh") or p.get("title") or "") + "）"
            n_clean += 1
    json.dump(papers, open(PAPERS, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print(f"已注入翻译 {n_tr} 篇；清理不准确表述 {n_clean} 篇。")

    # ---- 重建 site/index.html 的内联快照 ----
    html = open(INDEX, encoding="utf-8").read()
    marker = "const SNAPSHOT = "
    start = html.index(marker) + len(marker)
    end_script = html.index("</script>", start)
    arr_end = html.rindex("];", start, end_script) + 2  # 含 '];'
    dumped = json.dumps(papers, ensure_ascii=False)
    dumped = dumped.replace("</", "<\\/")  # 防止 </script> 提前闭合
    new_html = html[:start] + dumped + html[arr_end - 1:]  # 保留结尾 ';'
    open(INDEX, "w", encoding="utf-8").write(new_html)
    print("已重建 site/index.html 内联快照（共 %d 篇）" % len(papers))

if __name__ == "__main__":
    main()
